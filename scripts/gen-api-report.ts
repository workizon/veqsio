/**
 * Regenerates the coverage report in docs/api.md (the block between the GENERATED markers) from the real route table.
 *
 *   bun scripts/gen-api-report.ts          # rewrite docs/api.md
 *   bun scripts/gen-api-report.ts --check  # exit 1 when the committed report is out of date (not run in CI: other branches add routes)
 *
 * "Hand-written" = the operation has schemas/prose in packages/api/src/openapi/handwritten.ts.
 * "Outline only" = listed in the OpenAPI document from the route table (path, method, path parameters, authentication)
 * but without request/response schemas: these are the routes still to document.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

process.env.REDIS_URL ??= 'memory:';
process.env.DATABASE_URL ??= 'postgresql://veqsio:veqsio@localhost:5432/veqsio';
const root = join(import.meta.dir, '..');
const { default: app } = await import(join(root, 'packages/api/src/app.ts'));
const { collectRoutes, buildOpenApi } = await import(join(root, 'packages/api/src/openapi/spec.ts'));

const { included, excluded } = collectRoutes(app.routes);
const doc = buildOpenApi(app.routes);

const byTag = new Map<string, { hand: string[]; outline: string[] }>();
let hand = 0;
for (const r of included) {
  const op = doc.paths[r.openapiPath][r.method.toLowerCase()];
  const tag = op.tags[0] as string;
  if (!byTag.has(tag)) byTag.set(tag, { hand: [], outline: [] });
  const entry = `${r.method} ${r.openapiPath}`;
  if (op['x-documented'] === 'handwritten') { byTag.get(tag)!.hand.push(entry); hand++; } else byTag.get(tag)!.outline.push(entry);
}

const lines: string[] = [];
lines.push(`Generated by \`bun scripts/gen-api-report.ts\` from the route table of version ${doc.info.version}.`, '');
lines.push(`| | Operations |`, `|---|---|`);
lines.push(`| In the route table (listed in the OpenAPI document) | ${included.length} |`);
lines.push(`| Hand-written (request and response schemas, prose) | ${hand} |`);
lines.push(`| Outline only (path, method, parameters, authentication; no schemas) | ${included.length - hand} |`);
lines.push(`| Excluded on purpose | ${excluded.length} |`, '');
lines.push('### By area', '', '| Tag | Hand-written | Outline only |', '|---|---:|---:|');
for (const [tag, v] of [...byTag.entries()].sort(([a], [b]) => a.localeCompare(b))) lines.push(`| ${tag} | ${v.hand.length} | ${v.outline.length} |`);
lines.push('', '### Excluded routes', '');
for (const e of excluded) lines.push(`- \`${e.method} ${e.path}\`: ${e.reason}`);
lines.push('', '### Outline-only routes (not yet documented with schemas)', '');
for (const [tag, v] of [...byTag.entries()].sort(([a], [b]) => a.localeCompare(b))) {
  if (!v.outline.length) continue;
  lines.push(`<details><summary>${tag} (${v.outline.length})</summary>`, '', ...v.outline.sort().map((e) => `- \`${e}\``), '', '</details>', '');
}
const block = lines.join('\n');

const file = join(root, 'docs/api.md');
const text = readFileSync(file, 'utf8');
const BEGIN = '<!-- GENERATED:BEGIN -->';
const END = '<!-- GENERATED:END -->';
const a = text.indexOf(BEGIN), b = text.indexOf(END);
if (a < 0 || b < 0) throw new Error('docs/api.md has no GENERATED markers');
const next = text.slice(0, a + BEGIN.length) + '\n' + block + '\n' + text.slice(b);
if (process.argv.includes('--check')) {
  if (next !== text) { console.error('docs/api.md is out of date: run `bun scripts/gen-api-report.ts`'); process.exit(1); }
} else {
  writeFileSync(file, next);
  console.log(`docs/api.md updated: ${included.length} operations, ${hand} hand-written, ${included.length - hand} outline only`);
}
process.exit(0);
