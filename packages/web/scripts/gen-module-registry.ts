/**
 * Generates lib/module-registry.generated.ts: static imports of the web entry of every bundled module found in
 * modules/* and ee/modules/*. Next.js needs static imports, and community code must not name ee/ in committed source
 * (scripts/check-ee-boundary.sh), so the file is generated at build time and git-ignored. Without ee/ (or without
 * modules) it exports an empty list.
 */
import { existsSync, readdirSync, writeFileSync } from 'node:fs'
import { join, resolve } from 'node:path'

const web = process.cwd() // run from packages/web (npm scripts do)
const root = resolve(web, '../..')
const roots = [join(root, 'modules'), join(root, 'ee', 'modules')]
const found: Array<{ id: string; spec: string }> = []
for (const r of roots) {
  if (!existsSync(r)) continue
  for (const name of readdirSync(r).sort()) {
    if (existsSync(join(r, name, 'veqsio.module.json')) && existsSync(join(r, name, 'src', 'web.tsx'))) {
      const rel = join(r, name, 'src', 'web').slice(root.length + 1).split('\\').join('/')
      found.push({ id: name, spec: `../../../${rel}` })
    }
  }
}
const lines = [
  '// GENERATED by scripts/gen-module-registry.ts. Do not edit; it is git-ignored.',
  "import type { WebModuleDefinition } from '@veqsio/sdk'",
  ...found.map((f, i) => `import m${i} from '${f.spec}'`),
  `export const generatedModules: WebModuleDefinition[] = [${found.map((_, i) => `m${i}`).join(', ')}]`,
  '',
]
writeFileSync(join(web, 'lib', 'module-registry.generated.ts'), lines.join('\n'))
console.log(`[modules] web registry: ${found.length} module(s)${found.length ? ' (' + found.map((f) => f.id).join(', ') + ')' : ''}`)
