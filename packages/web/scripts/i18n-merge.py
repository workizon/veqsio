#!/usr/bin/env python3
"""Merges translated chunks into lib/i18n/auto-<lang>.ts.  usage: i18n-merge.py <dir with chunk-*.json/rank-*.json and tr-*.json>
A chunk <name>.json is a JSON list of English strings; tr-<name>.json holds {"ru": [...], "de": [...], "es": [...]} aligned by index (the lengths must match)."""
import json, sys, glob, os, re
d = sys.argv[1]; out = os.path.join(os.path.dirname(__file__), '..', 'lib', 'i18n')
langs = ['ru', 'de', 'es']; res = {l: {} for l in langs}; n = 0
for tf in sorted(glob.glob(os.path.join(d, 'tr-*.json'))):
    name = os.path.basename(tf)[3:]; src = os.path.join(d, name) if os.path.exists(os.path.join(d, name)) else os.path.join(d, 'chunk-' + name)
    keys = json.load(open(src)); tr = json.load(open(tf))
    for l in langs:
        if l not in tr: continue
        if len(tr[l]) != len(keys): sys.exit(f'{name}: {l} has {len(tr[l])} entries for {len(keys)} strings')
        for k, v in zip(keys, tr[l]):
            if not v.strip(): sys.exit(f'{name} {l}: empty translation for {k!r}')
            if sorted(re.findall(r'\{[a-zA-Z]+\}', k)) != sorted(re.findall(r'\{[a-zA-Z]+\}', v)): sys.exit(f'{name} {l}: placeholders differ for {k!r}')
            if v != k: res[l][k] = v
    n += len(keys)
for l in langs:
    body = ',\n'.join(f'  {json.dumps(k, ensure_ascii=False)}: {json.dumps(v, ensure_ascii=False)}' for k, v in sorted(res[l].items()))
    open(os.path.join(out, f'auto-{l}.ts'), 'w').write(f"// Generated by scripts/i18n-merge.py from reviewed translations. Hand-written entries in {l}.ts win over these.\nexport const auto{l.capitalize()}: Record<string, string> = {{\n{body},\n}}\n")
print(f'{n} strings, entries per language:', {l: len(v) for l, v in res.items()})
