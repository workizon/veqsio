/** Downloads the current configuration as CSV, XLSX or JSON (the server runs it as the signed-in user). */
export async function downloadExport(config: ViewConfig, format: 'csv' | 'xlsx' | 'json', name: string): Promise<void> {
  const res = await fetch('/rest/api/2/views/export', {
    method: 'POST', credentials: 'include', headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify({ config, format, name }),
  })
  if (!res.ok) {
    let msg = res.statusText
    try { msg = (await res.json()).errorMessages?.join(', ') || msg } catch { /* not json */ }
    throw new Error(msg)
  }
  const truncated = res.headers.get('X-Export-Truncated') === 'true'
  const match = /filename="([^"]+)"/.exec(res.headers.get('Content-Disposition') ?? '')
  const blob = await res.blob()
  const url = URL.createObjectURL(blob)
  const a = document.createElement('a')
  a.href = url
  a.download = match?.[1] ?? `export.${format}`
  document.body.appendChild(a)
  a.click()
  a.remove()
  URL.revokeObjectURL(url)
  if (truncated) throw new Error(trNow('The export was cut off at the row limit; narrow the query to get everything.'))
}
