import { useMutation, useQuery, useQueryClient } from '@tanstack/react-query'
import type { ApiIssue } from '@/hooks/use-issues'
import type { ViewConfig, ViewGroup, GroupField } from '@/lib/views'
import type { Share } from '@/components/share-dialog'
import { trNow } from '@/lib/tr'

async function api<T>(url: string, options?: RequestInit): Promise<T> {
  const res = await fetch(url, { ...options, credentials: 'include', headers: { 'Content-Type': 'application/json', ...(options?.headers ?? {}) } })
  if (!res.ok) {
    let msg = res.statusText
    let status = res.status
    try { msg = (await res.json()).errorMessages?.join(', ') || msg } catch { /* not json */ }
    throw Object.assign(new Error(msg), { status })
  }
  return res.json()
}

export interface ViewSummary {
  id: string
  builtin: boolean
  name: string
  description: string | null
  owner: { id: number | null; displayName: string | null } | null
  favourite: boolean
  editable: boolean
  shared: boolean
  layout: string
  query: string
  config?: ViewConfig
  shares?: Share[]
  updatedAt: string | null
}

export interface ViewList { startAt: number; maxResults: number; total: number; isLast: boolean; builtin: ViewSummary[]; values: ViewSummary[] }

export interface ViewResult {
  view: ViewSummary | null
  startAt: number
  maxResults: number
  total: number
  issues: ApiIssue[]
  groupBy: GroupField
  subGroupBy: GroupField
  showEmptyGroups: boolean
  groups: ViewGroup[]
}

export type ViewScope = 'all' | 'mine' | 'shared' | 'favourites'

export const viewKeys = {
  all: ['views'] as const,
  list: (scope: ViewScope, search: string) => ['views', 'list', scope, search] as const,
  one: (id: string) => ['views', 'one', id] as const,
}

const enc = encodeURIComponent
const isBuiltin = (id: string) => id.startsWith('builtin:')

export function useViewList(scope: ViewScope, search: string) {
  return useQuery({
    queryKey: viewKeys.list(scope, search),
    queryFn: () => api<ViewList>(`/rest/api/2/views?scope=${scope}&search=${enc(search)}&maxResults=100`),
  })
}

/** One view with its stored configuration (built-in views are generated by the server). */
export function useView(id: string) {
  return useQuery({
    queryKey: viewKeys.one(id),
    queryFn: () => api<ViewSummary>(isBuiltin(id) ? `/rest/api/2/views/builtin/${enc(id.slice(8))}` : `/rest/api/2/views/${enc(id)}`),
    retry: false,
  })
}

/** Executes a (possibly unsaved) configuration as the signed-in user. */
export function useViewResult(config: ViewConfig | null, startAt: number, maxResults: number) {
  return useQuery({
    queryKey: ['views', 'result', config, startAt, maxResults],
    enabled: !!config,
    queryFn: () => api<ViewResult>('/rest/api/2/views/execute', { method: 'POST', body: JSON.stringify({ config, startAt, maxResults }) }),
    placeholderData: (prev) => prev,
    retry: false,
  })
}

export function useCreateView() {
  const qc = useQueryClient()
  return useMutation({
    mutationFn: (body: { name: string; description?: string; config: ViewConfig; shares?: Share[]; favourite?: boolean }) =>
      api<ViewSummary>('/rest/api/2/views', { method: 'POST', body: JSON.stringify(body) }),
    onSuccess: () => qc.invalidateQueries({ queryKey: viewKeys.all }),
  })
}

