/**
 * Writes schema-version.ts from the migration journal so the bundled API knows how many
 * migrations it expects (the production image does not ship the drizzle folder).
 * Run automatically by `bun run db:generate`; CI fails when the committed file is stale.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const journal = JSON.parse(readFileSync(join(import.meta.dir, 'drizzle/meta/_journal.json'), 'utf8')) as {
  entries: Array<{ tag: string }>;
};
const last = journal.entries[journal.entries.length - 1];
const out = `// GENERATED by gen-schema-version.ts from drizzle/meta/_journal.json. Do not edit.
export const EXPECTED_MIGRATIONS = ${journal.entries.length}
export const LATEST_MIGRATION = ${JSON.stringify(last?.tag ?? '')}
`;
writeFileSync(join(import.meta.dir, 'schema-version.ts'), out);
console.log(`schema-version.ts: ${journal.entries.length} migration(s), latest ${last?.tag}`);
