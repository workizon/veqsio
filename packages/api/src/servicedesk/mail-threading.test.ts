import { describe, test, expect } from 'bun:test'
import {
  mailDomain, rootMessageId, newMessageId, parseMessageIds, issueKeyFromMessageId, issueKeyFromReferences,
  buildThreadHeaders, requestSubject, portalRequestUrl, textToHtml,
} from './mail-threading'

describe('mail threading helpers', () => {
  test('mailDomain prefers the sender address, then the web url', () => {
    expect(mailDomain('Desk <help@Example.COM>')).toBe('example.com')
    expect(mailDomain('help@acme.io')).toBe('acme.io')
    expect(mailDomain(null, 'https://veqsio.acme.io/x')).toBe('veqsio.acme.io')
    expect(mailDomain(null, 'http://localhost:3001')).toBe('veqsio.local')
    expect(mailDomain()).toBe('veqsio.local')
  })

  test('message ids encode the request key and round-trip', () => {
    const id = newMessageId('IT-12', 'acme.io', 'ab-cd_12')
    expect(id).toBe('<req.IT-12.abcd12@acme.io>')
    expect(issueKeyFromMessageId(id)).toBe('IT-12')
    expect(issueKeyFromMessageId(rootMessageId('IT-12', 'acme.io'))).toBe('IT-12')
    expect(issueKeyFromMessageId('<random@gmail.com>')).toBeNull()
    expect(issueKeyFromMessageId('<req.IT-12.x@a.io> trailing')).toBeNull()
  })

  test('parseMessageIds handles lists, folding and junk', () => {
    expect(parseMessageIds('<a@x> <b@y>\r\n <c@z>')).toEqual(['<a@x>', '<b@y>', '<c@z>'])
    expect(parseMessageIds(['<a@x>', '<a@x> <b@y>'])).toEqual(['<a@x>', '<b@y>'])
    expect(parseMessageIds(undefined)).toEqual([])
    expect(parseMessageIds('no ids here')).toEqual([])
  })

  test('issueKeyFromReferences only accepts keys of the desk project', () => {
    const ids = ['<other@x>', '<req.OPS-4.root@a.io>', '<req.IT-9.q@a.io>']
    expect(issueKeyFromReferences(ids, 'IT')).toBe('IT-9')
    expect(issueKeyFromReferences(ids, 'it')).toBe('IT-9')
    expect(issueKeyFromReferences(ids, 'HR')).toBeNull()
    // a project key that is a prefix of another must not match
    expect(issueKeyFromReferences(['<req.ITX-1.r@a.io>'], 'IT')).toBeNull()
  })

  test('buildThreadHeaders chains replies to the previous mail', () => {
    const first = buildThreadHeaders({ issueKey: 'IT-1', domain: 'a.io', token: 't1' })
    expect(first['In-Reply-To']).toBe('<req.IT-1.root@a.io>')
    expect(first.References).toBe('<req.IT-1.root@a.io>')
    expect(first['Message-ID']).toBe('<req.IT-1.t1@a.io>')
    expect(first['Auto-Submitted']).toBe('auto-replied')
    expect(first['Reply-To']).toBeUndefined()
    const second = buildThreadHeaders({ issueKey: 'IT-1', domain: 'a.io', token: 't2', previousId: first['Message-ID'], replyTo: 'help@a.io', autoGenerated: true })
    expect(second['In-Reply-To']).toBe(first['Message-ID'])
    expect(second.References).toBe(`<req.IT-1.root@a.io> ${first['Message-ID']}`)
    expect(second['Reply-To']).toBe('help@a.io')
    expect(second['Auto-Submitted']).toBe('auto-generated')
    expect(second['X-Auto-Response-Suppress']).toBe('All')
  })

  test('requestSubject is single line, bracketed and capped', () => {
    expect(requestSubject('IT-1', 'Printer\r\nBcc: evil@x.io')).toBe('[IT-1] Printer Bcc: evil@x.io')
    expect(requestSubject('IT-1', 'x'.repeat(1000)).length).toBe(300)
  })

  test('portalRequestUrl and textToHtml escape', () => {
    expect(portalRequestUrl('https://h.io/', 'it help', 'IT-1')).toBe('https://h.io/portal/it%20help/requests/IT-1')
    expect(textToHtml('a <b>"x"</b>\nline2 & more')).toBe('a &lt;b&gt;&quot;x&quot;&lt;/b&gt;<br/>line2 &amp; more')
  })
})
