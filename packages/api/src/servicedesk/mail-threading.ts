/**
 * Pure helpers for threading customer e-mail of a service desk request.
 *
 * Scheme: every request has a virtual root id `<req.KEY.root@domain>` that we never send but put in
 * References of every mail, so any client groups the whole conversation. Each mail we send carries its own
 * `<req.KEY.<token>@domain>`, In-Reply-To = the previous mail of the request (or the root) and
 * References = root + previous. Replies from customers carry one of these ids in In-Reply-To / References,
 * which is how the poller matches a mail to its request even when the subject was edited.
 */

export const MAX_SUBJECT = 300

/** Domain used in Message-IDs: the domain of the sender address, else the host of the web URL, else a fallback. */
export function mailDomain(from?: string | null, webUrl?: string | null): string {
  const m = /@([a-z0-9.-]+\.[a-z]{2,})>?\s*$/i.exec(from ?? '')
  if (m) return m[1].toLowerCase()
  try {
    const h = new URL(webUrl ?? '').hostname
    if (h && h !== 'localhost') return h.toLowerCase()
  } catch { /* fall through */ }
  return 'veqsio.local'
}

const keyPart = (issueKey: string) => issueKey.replace(/[^A-Za-z0-9-]/g, '')

export const rootMessageId = (issueKey: string, domain: string) => `<req.${keyPart(issueKey)}.root@${domain}>`
export const newMessageId = (issueKey: string, domain: string, token: string) =>
  `<req.${keyPart(issueKey)}.${token.replace(/[^A-Za-z0-9]/g, '')}@${domain}>`

/** All `<id>` tokens of a Message-ID / References / In-Reply-To header value (string or list). */
export function parseMessageIds(header: string | string[] | null | undefined): string[] {
  const raw = Array.isArray(header) ? header.join(' ') : header ?? ''
  const out: string[] = []
  for (const m of raw.matchAll(/<[^<>\s]{1,500}>/g)) if (!out.includes(m[0])) out.push(m[0])
  return out.slice(0, 50)
}

/** Request key encoded in one of our Message-IDs (`<req.KEY.token@domain>`), or null. */
export function issueKeyFromMessageId(id: string): string | null {
  const m = /^<req\.([A-Za-z0-9]+-\d{1,9})\.[A-Za-z0-9]+@[^<>\s]+>$/.exec(id)
  return m ? m[1].toUpperCase() : null
}

/** First request key found in any of the given ids that belongs to the project, or null. */
export function issueKeyFromReferences(ids: string[], projectKey: string): string | null {
  for (const id of ids) {
    const k = issueKeyFromMessageId(id)
    if (k && k.startsWith(`${projectKey.toUpperCase()}-`)) return k
  }
  return null
}

export interface ThreadHeaders {
  'Message-ID': string
  'In-Reply-To': string
  References: string
  'Reply-To'?: string
  'Auto-Submitted': string
  'X-Auto-Response-Suppress': string
}

/** Headers for one outbound mail of a request. `previousId` is the last mail we sent for it, if any. */
export function buildThreadHeaders(o: {
  issueKey: string; domain: string; token: string; previousId?: string | null; replyTo?: string | null; autoGenerated?: boolean
}): ThreadHeaders {
  const root = rootMessageId(o.issueKey, o.domain)
  const prev = o.previousId && o.previousId !== root ? o.previousId : null
  const h: ThreadHeaders = {
    'Message-ID': newMessageId(o.issueKey, o.domain, o.token),
    'In-Reply-To': prev ?? root,
    References: prev ? `${root} ${prev}` : root,
    // Keeps vacation responders from answering (loop protection); agent replies are still human-written
    'Auto-Submitted': o.autoGenerated ? 'auto-generated' : 'auto-replied',
    'X-Auto-Response-Suppress': 'All',
  }
  if (o.replyTo) h['Reply-To'] = o.replyTo
  return h
}

/** `[KEY-1] Summary`, one line, no header injection, capped. */
export function requestSubject(issueKey: string, summary: string): string {
  // eslint-disable-next-line no-control-regex
  const one = `[${issueKey}] ${summary}`.replace(/[\u0000-\u001f\u007f]+/g, ' ').replace(/\s+/g, ' ').trim()
  return one.length > MAX_SUBJECT ? `${one.slice(0, MAX_SUBJECT - 1)}…` : one
}

/** Portal link of a request. */
export function portalRequestUrl(webUrl: string, slug: string, issueKey: string): string {
  return `${webUrl.replace(/\/+$/, '')}/portal/${encodeURIComponent(slug)}/requests/${encodeURIComponent(issueKey)}`
}

/** Plain-text body to HTML: escaped, newlines kept. */
export function textToHtml(text: string): string {
  return text.replace(/[&<>"']/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c]!)).replace(/\r?\n/g, '<br/>')
}
